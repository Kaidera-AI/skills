#!/usr/bin/env node
'use strict'

// Canonical portable directories -> flat platform manifests. Metadata lives in SKILL.md.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const YAML = require('yaml')
const root = path.resolve(__dirname, '..')
const sha = value => crypto.createHash('sha256').update(value).digest('hex')
const names = ['design-selection', 'ui-design-engineering', 'gsd-core', 'hyperframes', 'ui-ux-review', 'web-interface-guidelines', 'folder-organisation']
const anchor = name => 'file-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-')

for (const name of names) {
  const directory = 'skills/development/' + name
  const files = []
  function walk(relative = '') {
    for (const entry of fs.readdirSync(path.join(root, directory, relative)).sort()) {
      const file = relative + entry
      const full = path.join(root, directory, file)
      const stat = fs.lstatSync(full)
      if (stat.isSymbolicLink()) throw new Error('Source symlink: ' + file)
      if (stat.isDirectory()) walk(file + '/')
      else if (stat.isFile() && entry.endsWith('.md')) files.push([file, fs.readFileSync(full, 'utf8')])
      else throw new Error('Unexpected source file: ' + file)
    }
  }
  walk()
  const entry = files.find(([file]) => file === 'SKILL.md')
  const parts = entry && entry[1].match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!parts) throw new Error('Missing canonical frontmatter: ' + name)
  const config = YAML.parse(parts[1], { uniqueKeys: true })
  if (config.name !== name) throw new Error('Source name mismatch: ' + name)
  const metadata = config.metadata
  function links(text, file) {
    return text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (whole, label, link) => {
      if (/^https?:|^#/.test(link)) return whole
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(file), link))
      if (!files.some(([candidate]) => candidate === resolved)) {
        throw new Error('Missing bundled reference: ' + name + '/' + file + ' -> ' + link)
      }
      return '[' + label + '](#' + anchor(resolved) + ')'
    })
  }
  const body = [
    '<!-- Generated by scripts/render-upstream-adapters.js from the canonical directory. -->',
    '<a id="' + anchor('SKILL.md') + '"></a>\n' + links(parts[2].trim(), 'SKILL.md'),
    ...files.filter(([file]) => file !== 'SKILL.md').map(([file, text]) =>
      '<a id="' + anchor(file) + '"></a>\n\n## Bundled file: ' + file + '\n\n' + links(text.trim(), file)),
  ].join('\n\n')
  const manifest = {
    name, version: metadata.version, description: config.description,
    kaidera: {
      category: 'development', trust_tier: 'unvetted', risk_level: metadata.risk_level,
      capabilities_required: metadata.capabilities_required,
      allowed_domains: metadata.allowed_domains,
      content_hash: sha(body.trim()), signed_by: '', last_reviewed: '', reviewer: '',
      source: {
        repo: 'Kaidera-AI/skills', path: directory,
        content_sha256: sha(JSON.stringify(files.map(([file, text]) => [file, sha(text)]))),
      },
    },
    author: 'Kaidera-AI', license: config.license, updated: metadata.updated,
    tags: metadata.tags,
    attribution_author: metadata.attribution_author,
    attribution_url: metadata.attribution_url,
    attribution_notes: metadata.attribution_notes,
    safety_constraints: metadata.safety_constraints,
  }
  const output = '---\n' + YAML.stringify(manifest, { lineWidth: 100 }) + '---\n\n' + body + '\n'
  const target = path.join(root, directory + '.SKILL.md')
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
      throw new Error('Projection drift: ' + name)
    }
  } else fs.writeFileSync(target, output)
  console.log(name + ': ' + files.length + ' source files; ' + manifest.kaidera.source.content_sha256)
}
