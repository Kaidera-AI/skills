#!/usr/bin/env node
'use strict'

// Directory source -> single-file catalogue projection. Never edit the projection.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const YAML = require('yaml')

const root = path.resolve(__dirname, '..')
const source = path.join(root, 'skills/development/development-workflow')
const target = path.join(root, 'skills/development/development-workflow.SKILL.md')
const sha = value => crypto.createHash('sha256').update(value).digest('hex')
const files = []
function walk(dir, prefix = '') {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name)
    const relative = prefix + name
    const stat = fs.lstatSync(full)
    if (stat.isSymbolicLink()) throw new Error('Source symlink: ' + relative)
    if (stat.isDirectory()) walk(full, relative + '/')
    else if (stat.isFile() && name.endsWith('.md')) {
      files.push([relative, fs.readFileSync(full, 'utf8')])
    } else throw new Error('Unexpected source file: ' + relative)
  }
}
walk(source)
const contentDigest = sha(JSON.stringify(files.map(([name, text]) => [name, sha(text)])))
const entry = files.find(([name]) => name === 'SKILL.md')[1]
const parts = entry.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
if (!parts) throw new Error('Missing canonical frontmatter')
const config = YAML.parse(parts[1], { uniqueKeys: true })
const anchor = name => 'file-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-')
function links(text, name) {
  return text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (whole, label, link) => {
    if (/^https?:|^#/.test(link)) return whole
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(name), link))
    if (!files.some(([candidate]) => candidate === resolved)) {
      throw new Error('Missing bundled reference: ' + name + ' -> ' + link)
    }
    return '[' + label + '](#' + anchor(resolved) + ')'
  })
}
const body = [
  '<!-- Generated by scripts/render-development-workflow.js from the canonical directory. -->',
  '<a id="' + anchor('SKILL.md') + '"></a>\n' + links(parts[2].trim(), 'SKILL.md'),
  ...files.filter(([name]) => name !== 'SKILL.md').map(([name, text]) =>
    '<a id="' + anchor(name) + '"></a>\n\n## Bundled file: ' + name + '\n\n' + links(text.trim(), name)),
].join('\n\n')
const manifest = {
  name: config.name,
  version: config.metadata.version,
  description: config.description,
  kaidera: {
    category: 'development', trust_tier: 'unvetted', risk_level: 'medium',
    capabilities_required: ['tool:file_read', 'tool:file_write', 'tool:code_interpreter', 'tool:web_search'],
    allowed_domains: ['github.com', 'c4model.com', 'csrc.nist.gov', 'google.github.io', 'www.peoplecert.org'],
    content_hash: sha(body.trim()), signed_by: '', last_reviewed: '', reviewer: '',
    source: { repo: 'Kaidera-AI/skills', path: 'skills/development/development-workflow', content_sha256: contentDigest },
  },
  author: 'Kaidera-AI', license: config.license, updated: '2026-09-23',
  tags: ['development', 'sdlc', 'ai-human', 'review', 'devsecops', 'service-management'],
  attribution_notes: 'Original generic process text from the Kaidera-AI operating model and the kaidera-sdlc lifecycle. External standards are cited as references, not reproduced.',
  safety_constraints: [
    'Development projects only. Repository-off mode prohibits Git probes and repository operations.',
    'No self-approval, fabricated human review, implicit release authority, or runtime trust promotion.',
    'External review applications require separate human authorization for source access, data, permissions and cost.',
  ],
}
const output = '---\n' + YAML.stringify(manifest, { lineWidth: 100 }) + '---\n\n' + body + '\n'
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('development-workflow projection drift')
    process.exit(1)
  }
} else {
  fs.writeFileSync(target, output)
}
console.log('development-workflow 1.0.0: ' + files.length + ' source files; source sha256 ' + contentDigest)
